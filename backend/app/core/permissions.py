def build_permissions_for_role(role_code: str) -> list[str]:
    permissions = list(AUTHENTICATED_PERMISSIONS)
    if role_code == "ADMIN":
        permissions.extend(ADMIN_PERMISSIONS)
    if role_code == "INV_BOUTIQUE":
        permissions.extend(INV_BOUTIQUE_PERMISSIONS)
    if role_code == "INV_TALLER":
        permissions.extend(INV_TALLER_PERMISSIONS)
    if role_code == "CAJA":
        permissions.extend(CAJA_PERMISSIONS)
    if role_code == "MODISTA":
        permissions.extend(MODISTA_PERMISSIONS)
    return sorted(set(permissions))


def build_policy_lines() -> list[str]:
    role_codes = ("ADMIN", "INV_TALLER", "INV_BOUTIQUE", "CAJA", "MODISTA")
    lines: list[str] = []
    for role_code in role_codes:
        for permission in build_permissions_for_role(role_code):
            lines.append(f"p, {role_code}, {permission}, use")
    for role_code in role_codes:
        lines.append(f"g, {role_code}, {role_code}")
    return lines
